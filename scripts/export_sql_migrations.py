"""Export the PostgreSQL DDL for migration 001 to migrations/001_initial_schema.sql.

The pipeline applies migrations automatically (`trendpulse migrate` / every run);
this file exists so the schema can be reviewed, diffed in PRs, or applied by hand
in the Supabase SQL editor.  Regenerate after changing storage/schema.py:

    python scripts/export_sql_migrations.py
"""

from __future__ import annotations

from pathlib import Path

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from trendpulse.storage import schema as s

MIG_DIR = Path(__file__).resolve().parents[1] / "migrations"


def _ddl(table, dialect) -> list[str]:
    out = [str(CreateTable(table, if_not_exists=True).compile(dialect=dialect)).strip() + ";"]
    for idx in sorted(table.indexes, key=lambda i: i.name):
        out.append(str(CreateIndex(idx, if_not_exists=True).compile(dialect=dialect)).strip() + ";")
    return out + [""]


def main() -> None:
    from trendpulse.storage.migrations import MIGRATIONS, TABLES_BY_VERSION

    dialect = postgresql.dialect()
    later = {n for names in TABLES_BY_VERSION.values() for n in names}
    parts = [
        "-- TrendPulse migration 001: initial medallion schema (generated by scripts/export_sql_migrations.py)",
        "-- Applied automatically by the pipeline; safe to run by hand in the Supabase SQL editor.",
        f"CREATE SCHEMA IF NOT EXISTS {s.PG_SCHEMA};",
        f"SET search_path TO {s.PG_SCHEMA};",
        "-- Keep the warehouse out of Supabase's auto-generated REST API.",
        f"REVOKE ALL ON SCHEMA {s.PG_SCHEMA} FROM anon, authenticated;",
        "",
    ]
    for table in s.metadata.sorted_tables:
        if table.name not in later:
            parts += _ddl(table, dialect)
    parts.append("INSERT INTO schema_migrations (version, description, applied_at) VALUES "
                 "(1, 'initial medallion schema (bronze/silver/gold + operational metadata)', now()) "
                 "ON CONFLICT (version) DO NOTHING;")
    (MIG_DIR / "001_initial_schema.sql").write_text("\n".join(parts) + "\n")
    print("wrote migrations/001_initial_schema.sql")
    for m in MIGRATIONS:
        if m.version == 1:
            continue
        body = [f"-- TrendPulse migration {m.version:03d}: {m.description} (generated)",
                f"SET search_path TO {s.PG_SCHEMA};", ""]
        for name in TABLES_BY_VERSION.get(m.version, []):
            body += _ddl(s.metadata.tables[name], dialect)
        body.append(f"INSERT INTO schema_migrations (version, description, applied_at) VALUES "
                    f"({m.version}, '{m.description}', now()) ON CONFLICT (version) DO NOTHING;")
        slug = "_".join(TABLES_BY_VERSION.get(m.version, ["migration"]))
        path = MIG_DIR / f"{m.version:03d}_{slug}.sql"
        path.write_text("\n".join(body) + "\n")
        print(f"wrote {path.relative_to(MIG_DIR.parent)}")


if __name__ == "__main__":
    main()
